def feature_ablation(X, k=4,
                     random_state=42):
    """
    Feature redundancy check.
    Compare clustering quality across
    different feature subsets.
    """
    configs = {
        '[base, pre, delta]': X[:, [0, 1, 2]],
        '[delta] only':       X[:, [2]],
        '[base, delta]':      X[:, [0, 2]],
        '[base, pre]':        X[:, [0, 1]],
        '[pre] only':         X[:, [1]],
        '[base] only':        X[:, [0]],
    }

    results = {}
    for name, Xf in configs.items():
        scaler = StandardScaler()
        Xs = scaler.fit_transform(Xf)

        km = KMeans(n_clusters=k, n_init=10,
                    random_state=random_state)
        labels = km.fit_predict(Xs)
        sil_k = silhouette_score(Xs, labels)

        best_sil, best_k = -1, 2
        for ki in range(2, 7):
            km_i = KMeans(n_clusters=ki,
                          n_init=10,
                          random_state=random_state)
            s = silhouette_score(
                Xs, km_i.fit_predict(Xs))
            if s > best_sil:
                best_sil, best_k = s, ki

        archetypes = {}
        for c in range(k):
            mask = labels == c
            archetypes[c] = {
                'n': int(mask.sum()),
                'delta': float(X[mask, 2].mean())
            }

        results[name] = {
            f'sil_k{k}': sil_k,
            'best_sil': best_sil,
            'best_k': best_k,
            'archetypes': archetypes
        }

    return results


def anchor_specificity_test(sessions,
                            embeddings,
                            n_perm=1000,
                            window=20,
                            step=10,
                            k=4):
    """
    Anchor specificity: compare clustering quality
    between real anchors and random positions.

    Args:
        sessions: list of session dicts
        embeddings: dict {sid: embedding array}

    Returns:
        dict with real_sil, random distribution,
        p_value
    """
    sess_dict = {s['dialogue_id']: s
                 for s in sessions}

    def get_features_at(la_seq, anchor_w):
        if la_seq is None or anchor_w < 3:
            return None
        std = np.std(la_seq)
        if std < 1e-10:
            return None
        la_n = (la_seq - np.mean(la_seq)) / std
        base = np.mean(la_n[:3])
        pre = np.mean(
            la_n[max(0, anchor_w - 3):anchor_w])
        return [base, pre, pre - base]

    def compute_anchor_w(sess, n_windows):
        client_turns = [
            t for t in sess['turns']
            if t['speaker'] == '내담자']
        risk_idx = [
            i for i, t in enumerate(client_turns)
            if t.get('risk') == 1]
        if not risk_idx:
            return None
        first_risk = risk_idx[0]
        n_client = len(client_turns)
        aw = int(first_risk / n_client * n_windows)
        return min(max(aw, 3), n_windows - 1)

    # Build session data
    session_data = {}
    real_rows = []

    for sid, emb in embeddings.items():
        sess = sess_dict.get(sid)
        if sess is None:
            continue
        la_seq = sliding_window_levy(
            emb, window=window, step=step)
        if la_seq is None:
            continue
        aw = compute_anchor_w(sess, len(la_seq))
        if aw is None:
            continue
        feat = get_features_at(la_seq, aw)
        if feat:
            real_rows.append(feat)
            session_data[sid] = {
                'la_seq': la_seq,
                'anchor_w': aw
            }

    X_real = np.array(real_rows)
    Xs_real = StandardScaler().fit_transform(X_real)
    km = KMeans(n_clusters=k,
                random_state=42, n_init=10)
    real_sil = silhouette_score(
        Xs_real, km.fit_predict(Xs_real))

    # Random anchor permutations
    np.random.seed(42)
    rand_sils = []

    for perm in range(n_perm):
        rows = []
        for sid, d in session_data.items():
            la_seq = d['la_seq']
            rand_w = np.random.randint(
                3, len(la_seq))
            feat = get_features_at(la_seq, rand_w)
            if feat:
                rows.append(feat)
        if len(rows) < 10:
            continue
        X = np.array(rows)
        Xs = StandardScaler().fit_transform(X)
        km_r = KMeans(n_clusters=k,
                      random_state=perm,
                      n_init=3, max_iter=100)
        rand_sils.append(
            silhouette_score(
                Xs, km_r.fit_predict(Xs)))

    rand_sils = np.array(rand_sils)
    p_val = np.mean(rand_sils >= real_sil)

    return {
        'n_sessions': len(real_rows),
        'real_sil': real_sil,
        'random_mean': rand_sils.mean(),
        'random_std': rand_sils.std(),
        'p_value': p_val,
        'random_distribution': rand_sils
    }